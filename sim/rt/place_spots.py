"""패널을 걸 수 있는 후보 자리 (교실 kr40: 가로 7.5 x 세로 9.0 x 높이 2.7 m).
좌표: x = 칠판 벽을 따라 (창 쪽 0 -> 복도 쪽 7.5), y = 앞(칠판 0) -> 뒤(9.0), z = 높이.
rt_paths.py (전파 길 구하기)와 place_study.py (자리 찾기)가 같이 쓴다. sionna 없이 불러올 수 있게 따로 두었다."""

# real2: 손이 닿는 스무 곳 (rt_paths.py 의 SPOTS3["real2"] 와 같은 차례)
REAL2 = [(1.95, 0.10, 1.95), (3.75, 0.10, 1.95), (5.55, 0.10, 1.95), (3.75, 1.15, 1.15), (0.45, 0.45, 1.60), (7.05, 0.45, 1.60),
         (0.08, 2.50, 2.00), (0.08, 4.85, 2.00), (0.08, 7.00, 2.00), (0.14, 4.85, 1.05), (7.42, 0.85, 2.00), (7.42, 4.85, 1.95), (7.42, 8.15, 2.00),
         (1.50, 8.42, 1.35), (3.75, 8.42, 1.35), (6.00, 8.42, 1.35), (3.75, 8.92, 2.00), (7.42, 2.50, 1.95), (7.42, 7.00, 1.95), (0.08, 1.00, 2.00)]
REAL2_NAMES = ["칠판 윗변 왼쪽 끝", "칠판 윗변 가운데", "칠판 윗변 오른쪽 끝", "교탁 위", "앞 창 쪽 모서리 삼각대 1.6m", "앞 복도 쪽 모서리 삼각대 1.6m",
               "창 유리 앞쪽 2.0m", "창 유리 가운데 2.0m", "창 유리 뒤쪽 2.0m", "창턱 가운데 1.05m", "앞문 위 2.0m", "복도 창턱 가운데 1.95m", "뒷문 위 2.0m",
               "사물함 위 왼쪽", "사물함 위 가운데", "사물함 위 오른쪽", "뒷벽 가운데 2.0m", "복도 창턱 앞쪽 1.95m", "복도 창턱 뒤쪽 1.95m", "창 유리 맨 앞 2.0m"]

SIDE_Y = (0.6, 1.5, 2.5, 3.5, 4.5, 5.5, 6.5, 7.5, 8.4)          # 옆벽을 따라 (앞에서 m). 첫 줄 책상은 y 2.0, 마지막 줄은 7.7
CEIL_Z = 2.62


def grid_spots():
    """3차원 자리 찾기 후보 102곳. 창 벽(유리, 0.9~2.4 m)과 복도 벽은 높이 1.6·2.0·2.35 m, 앞벽은 칠판(0.9~2.1 m) 위 2.3·2.55 m 와
    칠판 양옆, 뒷벽은 사물함(1.2 m) 위 1.6·2.0·2.4 m, 천장은 2.62 m 에 1.5~1.85 m 간격"""
    S = []
    for y in SIDE_Y:                                           # 창 쪽 벽 x=0 (유리에 흡착판)
        for z in (1.6, 2.0, 2.35):
            S.append((0.08, y, z))
    for y in SIDE_Y:                                           # 복도 쪽 벽 x=7.5 (문 자리는 문 위 2.35 m 만)
        for z in ((2.35,) if y in (0.6, 8.4) else (1.6, 2.0, 2.35)):
            S.append((7.42, y, z))
    for x in (1.5, 2.6, 3.75, 4.9, 6.0):                       # 앞벽: 칠판 위
        for z in (2.3, 2.55):
            S.append((x, 0.10, z))
    for x in (0.6, 6.9):                                       # 앞벽: 칠판 양옆
        for z in (1.6, 2.0, 2.35):
            S.append((x, 0.10, z))
    for x in (0.6, 1.7, 2.8, 3.75, 4.7, 5.8, 6.9):             # 뒷벽: 사물함 위
        for z in (1.6, 2.0, 2.4):
            S.append((x, 8.92, z))
    for x in (1.9, 3.75, 5.6):                                 # 천장
        for y in (2.0, 3.5, 5.0, 6.5, 8.0):
            S.append((x, y, CEIL_Z))
    return S


def all_spots():
    """real2 20곳 + grid 102곳 = 122곳 (kr40_tg 의 차례)"""
    return REAL2 + grid_spots()


def where(p):
    """벽 이름: 창, 복도, 앞, 뒤, 천장, 안 (교탁·사물함 위처럼 방 안에 올려 둔 것)"""
    x, y, z = p
    if z >= 2.6:
        return "천장"
    if x < 0.2:
        return "창"
    if x > 7.3:
        return "복도"
    if y < 0.2:
        return "앞"
    if y > 8.8:
        return "뒤"
    return "안"


def name(p, i=None):
    if i is not None and i < len(REAL2):
        return REAL2_NAMES[i]
    x, y, z = p; w = where(p)
    if w == "천장":
        return "천장 (창에서 %.1f, 앞에서 %.1f m)" % (x, y)
    if w in ("창", "복도"):
        return "%s 벽 앞에서 %.1f m, 높이 %.2f m" % (w, y, z)
    if w in ("앞", "뒤"):
        return "%s벽 창에서 %.1f m, 높이 %.2f m" % (w, x, z)
    return "(%.1f, %.1f, %.2f)" % (x, y, z)


def reach(p):
    """사다리 없이 걸 수 있나 (손 2.0 m 까지). 천장과 2.3 m 넘는 곳은 사다리나 고정 설치"""
    return p[2] <= 2.05
